// Spike A (research R7): echo duplication per run and the headphones-notice decision.
import { ECHO_CONDITIONS, type EchoConditionId, type RunMeta } from './echo-runs';
import { findEchoDuplicates, type EchoResult, type TimedText } from './scoring';

export const ECHO_NOTICE_THRESHOLD = 0.05;

export interface EchoRunResult {
  folder: string;
  condition: EchoConditionId;
  durationMs: number;
  /** echoCancellation as Chrome applied it (from run.json), or null if not reported. */
  appliedEchoCancellation: unknown;
  echo: EchoResult;
  /** Session errors, e.g. "tab: network"; a run with errors is not used for the decision. */
  errors: string[];
}

export function scoreRun(
  folder: string,
  meta: RunMeta,
  streams: { tab: readonly TimedText[]; mic: readonly TimedText[]; errors: string[] },
): EchoRunResult {
  return {
    folder,
    condition: meta.condition,
    durationMs: meta.durationMs,
    appliedEchoCancellation: meta.appliedMic.echoCancellation ?? null,
    echo: findEchoDuplicates(streams.mic, streams.tab),
    errors: streams.errors,
  };
}

export interface EchoRecommendation {
  /** null = inconclusive. */
  showNotice: boolean | null;
  text: string;
}

const pct = (x: number) => `${(x * 100).toFixed(1)} %`;

export function recommendEcho(results: readonly EchoRunResult[]): EchoRecommendation {
  const run2 = results.find((r) => r.condition === 'speakers-aec-on' && r.errors.length === 0);
  if (!run2 || run2.echo.remoteLines === 0) {
    return {
      showNotice: null,
      text: 'Inconclusive: run 2 (laptop speakers, echo cancellation on) is missing, failed, or has no remote lines. Record it again and re-run `pnpm spike:echo`.',
    };
  }
  if (run2.echo.rate > ECHO_NOTICE_THRESHOLD) {
    return {
      showNotice: true,
      text: `Run 2 duplicated ${pct(run2.echo.rate)} of remote lines under your name (above the 5 % bar). Ship the FR-028 headphones notice in 001 (tasks T087–T088, build flag HEADPHONES_NOTICE on), and consider an echo-suppression filter (drop mic lines matching the duplicate rule) as a follow-up task for you to approve.`,
    };
  }
  return {
    showNotice: false,
    text: `Run 2 duplicated ${pct(run2.echo.rate)} of remote lines (at or below the 5 % bar). Chrome's echo cancellation is enough: do not ship the headphones notice (T087–T088 are skipped, HEADPHONES_NOTICE off).`,
  };
}

export interface EchoFindingsInput {
  date: string;
  chromeVersion: string | null;
  results: readonly EchoRunResult[];
  recommendation: EchoRecommendation;
}

export function renderEchoFindings(input: EchoFindingsInput): string {
  const runOf = (id: EchoConditionId) => ECHO_CONDITIONS.find((c) => c.id === id)?.run ?? 0;
  const sorted = [...input.results].sort((a, b) => runOf(a.condition) - runOf(b.condition));
  const errors = sorted.filter((r) => r.errors.length > 0);
  return [
    '# Spike A findings: echo without headphones',
    '',
    `Generated by \`pnpm spike:echo\` on ${input.date} (Chrome ${input.chromeVersion ?? 'unknown'}). Method: research R7 — each run's tab and mic recordings streamed in parallel through ElevenLabs Scribe v2 Realtime; a mic line is an echo duplicate of a remote (tab) line when they are within ±1.5 s and at least 60 % of the mic line's words occur in the remote line. Only counts are recorded here; recognised text stays in the gitignored \`spikes/data/echo/results/\`.`,
    '',
    '## Duplication per run',
    '',
    '| Run | Condition | Remote lines | Duplicated remote lines | Rate | Mic lines | Echo cancellation applied | Duration |',
    '|-----|-----------|--------------|-------------------------|------|-----------|---------------------------|----------|',
    ...sorted.map(
      (r) =>
        `| ${runOf(r.condition)} | ${r.condition} | ${r.echo.remoteLines} | ${r.echo.duplicatedRemoteLines} | ${pct(r.echo.rate)} | ${r.echo.micLines} | ${JSON.stringify(r.appliedEchoCancellation)} | ${(r.durationMs / 1000).toFixed(0)} s |`,
    ),
    '',
    '## Recommendation',
    '',
    input.recommendation.text,
    '',
    '## Errors',
    '',
    errors.length === 0 ? 'None.' : errors.map((r) => `- ${r.folder}: ${r.errors.join('; ')}`).join('\n'),
    '',
    '## Your notes',
    '',
    '- Setup (laptop model, speaker volume, room, who was reading):',
    '- Did the duplicated lines in the raw results look like real echoes?',
    '- Decision (T048): headphones notice ships / does not ship',
    '',
  ].join('\n');
}
