export const SUPPORTED_LANGUAGES: readonly Language[] = [
  ...PINNED_LANGUAGES,
  ...[...OTHERS].sort((a, b) => a.name.localeCompare(b.name)),
];

export function languageName(code: string): string {
  return SUPPORTED_LANGUAGES.find((l) => l.code === code)?.name ?? code;
}
